/**
 * Точка входа мини-аппа.
 *
 * Панель вызывает эту функцию один раз и монтирует то, что она вернёт, как
 * обычный свой компонент. В контексте приходит её Vue, её компоненты, перевод,
 * вызов ручек модуля и уведомления — см. `ModuleHostContext` в панели.
 *
 * Контекст передаётся аргументом, а не импортируется: модуль собирается отдельно
 * от панели и про её внутренние пути ничего не знает.
 */
import Rewards from './Rewards.vue'

export default function (ctx) {
    // Компонент оборачивается, чтобы контекст попал внутрь через provide:
    // прокидывать его пропсами через каждый уровень было бы утомительно.
    return ctx.vue.defineComponent({
        name: 'PlaytimeRewardsApp',
        setup() {
            ctx.vue.provide('noro', ctx)
            return () => ctx.vue.h(Rewards)
        },
    })
}
